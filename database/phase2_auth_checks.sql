SELECT name,OBJECT_NAME(parent_object_id) AS parent_table,OBJECT_NAME(referenced_object_id) AS referenced_table
FROM sys.foreign_keys WHERE referenced_object_id IN (OBJECT_ID('dbo.THANH_VIEN'),OBJECT_ID('dbo.QTV'));
SELECT LOWER(LTRIM(RTRIM(THANH_VIEN_EMAIL))) AS email,COUNT(*) AS total
FROM dbo.THANH_VIEN WHERE THANH_VIEN_EMAIL IS NOT NULL
GROUP BY LOWER(LTRIM(RTRIM(THANH_VIEN_EMAIL))) HAVING COUNT(*)>1;
